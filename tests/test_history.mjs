import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const context = {};
const source = new URL('../web/history-model.js', import.meta.url);
assert.ok(fs.existsSync(source), 'History search model must exist');
vm.runInNewContext(fs.readFileSync(source, 'utf8'), context);
const {rank, prepare, filter, timeIndex, PAGE_SIZE} = context.BasilHistory;
assert.ok(rank({title:'Déjà Vu',artist:'Beyoncé'}, 'BEY deja') > 0);
assert.ok(rank({title:'Massive Attack',artist:'Someone'}, 'msvatk') > 0);
assert.equal(rank({title:'Blue',artist:'Miles'}, 'pink'), 0);
assert.ok(rank({title:'Blue',artist:'Miles'}, 'blue') > rank({title:'Beautiful Little Universe Echo',artist:'Miles'}, 'blue'));
const entries = prepare(Array.from({length:5001}, (_,i)=>({id:String(i), timestamp:1000+i*60, title:'Déjà Vu',artist:'Beyoncé',status:i%2?'played':'queued'})));
assert.equal(entries.length, 5001);
assert.equal(entries[0].timestamp, 301000);
assert.equal(filter(entries, 'bey deja').length, 5001);
assert.equal(timeIndex(entries, 0), 0);
assert.equal(timeIndex(entries, 1000), 5000);
assert.equal(timeIndex(entries, 500), 2500);
assert.equal(timeIndex([], 300), 0);
assert.ok(PAGE_SIZE <= 100);
assert.equal(prepare([{timestamp:'bogus'},{timestamp:null},{timestamp:123,status:'mystery'}]).length, 0);
console.log('PASS: accent/token/subsequence ranking, newest-first ordering, 5,001-entry full-range time seeking, invalid records rejected.');
